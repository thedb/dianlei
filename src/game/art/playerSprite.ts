/**
 * Create the full player sprite sheet with all 11 bank frames
 */
export function createPlayerSpriteSheet(): PlayerSpriteSheet {
  const rightFrameData: SpriteData[] = [
    PLAYER_CENTER,
    PLAYER_BANK_R1,
    PLAYER_BANK_R2,
    PLAYER_BANK_R3,
    PLAYER_BANK_R4,
    PLAYER_BANK_R5,
  ];
  const rightNozzles: NozzleOffset[][] = [
    NOZZLES_CENTER,
    NOZZLES_R1,
    NOZZLES_R2,
    NOZZLES_R3,
    NOZZLES_R4,
    NOZZLES_R5,
  ];

  const bankFrames: BankFrame[] = [];

  // Frames 0-4: Left bank (mirrored from right frames 5-1)
  for (let i = 5; i >= 1; i--) {
    const frameData = rightFrameData[i]!;
    const nozzles = rightNozzles[i]!;
    const frame = renderSpriteMirrored(frameData, 0.5, 0.5);
    const mirroredNozzles = nozzles.map((n) => ({ x: -n.x, y: n.y }));
    bankFrames.push({ ...frame, nozzles: mirroredNozzles });
  }

  // Frame 5: Center
  const centerFrame = renderSprite(PLAYER_CENTER, 0.5, 0.5);
  bankFrames.push({ ...centerFrame, nozzles: NOZZLES_CENTER });

  // Frames 6-10: Right bank
  for (let i = 1; i <= 5; i++) {
    const frameData = rightFrameData[i]!;
    const nozzles = rightNozzles[i]!;
    const frame = renderSprite(frameData, 0.5, 0.5);
    bankFrames.push({ ...frame, nozzles });
  }

  return {
    bankFrames,
    frameCount: 11,
    width: 28,
    height: 32,
  };
}

/** Get the bank frame index (0-10) from bank value (-1 to 1) */
export function getBankFrameIndex(bank: number): number {
  // bank: -1 = full left (frame 0), 0 = center (frame 5), 1 = full right (frame 10)
  const normalized = (bank + 1) / 2; // 0 to 1
  return Math.round(normalized * 10);
}
